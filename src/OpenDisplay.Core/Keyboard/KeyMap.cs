namespace OpenDisplay.Core.Keyboard;

/// <summary>Translates Windows virtual keys to macOS virtual key codes (kVK_*, US layout positions).</summary>
public static class KeyMap
{
    // Windows VK -> macOS kVK for keys that are not modifiers.
    private static readonly Dictionary<int, int> Plain = new()
    {
        // Letters
        [0x41] = 0x00, [0x42] = 0x0B, [0x43] = 0x08, [0x44] = 0x02, [0x45] = 0x0E, [0x46] = 0x03,
        [0x47] = 0x05, [0x48] = 0x04, [0x49] = 0x22, [0x4A] = 0x26, [0x4B] = 0x28, [0x4C] = 0x25,
        [0x4D] = 0x2E, [0x4E] = 0x2D, [0x4F] = 0x1F, [0x50] = 0x23, [0x51] = 0x0C, [0x52] = 0x0F,
        [0x53] = 0x01, [0x54] = 0x11, [0x55] = 0x20, [0x56] = 0x09, [0x57] = 0x0D, [0x58] = 0x07,
        [0x59] = 0x10, [0x5A] = 0x06,
        // Digits row
        [0x30] = 0x1D, [0x31] = 0x12, [0x32] = 0x13, [0x33] = 0x14, [0x34] = 0x15,
        [0x35] = 0x17, [0x36] = 0x16, [0x37] = 0x1A, [0x38] = 0x1C, [0x39] = 0x19,
        // Punctuation (OEM keys, US positions)
        [0xBA] = 0x29, [0xBB] = 0x18, [0xBC] = 0x2B, [0xBD] = 0x1B, [0xBE] = 0x2F, [0xBF] = 0x2C,
        [0xC0] = 0x32, [0xDB] = 0x21, [0xDC] = 0x2A, [0xDD] = 0x1E, [0xDE] = 0x27,
        // Editing and whitespace
        [0x08] = 0x33, // Backspace -> Delete
        [0x09] = 0x30, // Tab
        [0x0D] = 0x24, // Enter (keypad Enter handled below)
        [0x1B] = 0x35, // Esc
        [0x20] = 0x31, // Space
        [0x14] = 0x39, // Caps Lock
        [0x2E] = 0x75, // Delete -> Forward Delete
        [0x2D] = 0x72, // Insert -> Help
        // Navigation
        [0x21] = 0x74, [0x22] = 0x79, [0x23] = 0x77, [0x24] = 0x73,
        [0x25] = 0x7B, [0x26] = 0x7E, [0x27] = 0x7C, [0x28] = 0x7D,
        // Function keys
        [0x70] = 0x7A, [0x71] = 0x78, [0x72] = 0x63, [0x73] = 0x76, [0x74] = 0x60, [0x75] = 0x61,
        [0x76] = 0x62, [0x77] = 0x64, [0x78] = 0x65, [0x79] = 0x6D, [0x7A] = 0x67, [0x7B] = 0x6F,
        [0x7C] = 0x69, [0x7D] = 0x6B, [0x7E] = 0x71,
        // Keypad
        [0x60] = 0x52, [0x61] = 0x53, [0x62] = 0x54, [0x63] = 0x55, [0x64] = 0x56,
        [0x65] = 0x57, [0x66] = 0x58, [0x67] = 0x59, [0x68] = 0x5B, [0x69] = 0x5C,
        [0x6A] = 0x43, [0x6B] = 0x45, [0x6D] = 0x4E, [0x6E] = 0x41, [0x6F] = 0x4B,
        [0x90] = 0x47, // Num Lock -> keypad Clear
    };

    public const int MacCommand = 0x37, MacShift = 0x38, MacOption = 0x3A, MacControl = 0x3B;
    public const int MacRightCommand = 0x36, MacRightShift = 0x3C, MacRightOption = 0x3D, MacRightControl = 0x3E;

    /// <param name="vk">Windows virtual key (wParam of WM_KEYDOWN).</param>
    /// <param name="extended">lParam bit 24: distinguishes right Ctrl/Alt and keypad Enter.</param>
    /// <param name="scanCode">lParam bits 16-23: distinguishes right Shift (0x36).</param>
    /// <param name="ctrlIsCommand">
    /// True: left Ctrl acts as Command, so Windows habits (Ctrl+C, Ctrl+V) work on the Mac,
    /// and right Ctrl is Control. False: both Ctrl keys are Control.
    /// </param>
    /// <returns>The macOS key code, or null for keys the Mac has no equivalent for.</returns>
    public static int? ToMac(int vk, bool extended, int scanCode, bool ctrlIsCommand = true)
    {
        switch (vk)
        {
            case 0x10: // Shift
            case 0xA0:
            case 0xA1:
                return vk == 0xA1 || scanCode == 0x36 ? MacRightShift : MacShift;
            case 0x11: // Ctrl
            case 0xA2:
            case 0xA3:
            {
                bool right = vk == 0xA3 || extended;
                if (!ctrlIsCommand) return right ? MacRightControl : MacControl;
                return right ? MacControl : MacCommand;
            }
            case 0x12: // Alt
            case 0xA4:
            case 0xA5:
                return vk == 0xA5 || extended ? MacRightOption : MacOption;
            case 0x5B: // Windows keys -> Control (when Windows lets them through)
            case 0x5C:
                return ctrlIsCommand ? MacControl : MacCommand;
            case 0x0D when extended:
                return 0x4C; // keypad Enter
        }
        return Plain.TryGetValue(vk, out int mac) ? mac : null;
    }
}
